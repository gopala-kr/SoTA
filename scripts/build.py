def latest_posts(manifest, n=8):
    """Newest posts first: by date, then by manifest order (new posts are added at the top)."""
    order = {slug: i for i, slug in enumerate(manifest)}
    return sorted(manifest.values(), key=lambda p: (p["date"], -order[p["slug"]]), reverse=True)[:n]


def render_latest_block(manifest, series_owner):
    """Homepage "Latest from the Academy": newest posts, each with a trail of its thread (series)."""
    cards = []
    for p in latest_posts(manifest):
        ser = series_owner.get(p["slug"])
