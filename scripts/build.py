def validate_content():
    """Loop verifier for authored content (default: reject). See docs/LOOP-ENGINEERING.md.
    1. Pages in the agent, evaluation and Maestro series (and listed hub pages) that mention Anthropic or Claude carry the disclosure.
    2. Every Maestro code block matches its file in data/code/<slug>/, and was either run (its output shown) or is labelled 'not executed'.
    3. Every Maestro section headed '(scenario)' carries a scenario box.
    4. The required validators are still wired into this script (guards against weakening the gate)."""
    import html as _html
    problems = []
    series_path = ROOT / "blog/series.json"
    slugs = set()
    if series_path.exists():
        for ser in json.loads(series_path.read_text(encoding="utf-8")).get("series", []):
            ss = ser.get("slugs", [])
            if any(x in ss for x in DISCLOSE_SERIES):
                slugs.update(ss)
    files = [ROOT / "blog" / f"{x}.html" for x in sorted(slugs)] + [ROOT / p for p in DISCLOSE_PAGES]
    for f in files:
        if not f.exists():
            continue
        txt = f.read_text(encoding="utf-8")
        body = txt[txt.find("<main"):] if "<main" in txt else txt
        if re.search(r"Anthropic|Claude", body) and "Disclosure" not in body:
            problems.append(f"{f.relative_to(ROOT)}: mentions Anthropic/Claude but has no disclosure")
    for f in sorted((ROOT / "blog").glob("maestro-*.html")):
        txt, slug = f.read_text(encoding="utf-8"), f.stem
        outs = " ".join(_html.unescape(o) for o in re.findall(r'class="mo-out"[^>]*>(.*?)</div>', txt, re.S))
        for head, pre in re.findall(r'<div class="mo-code"><div class="h"><span>(.*?)</span>.*?<pre>(.*?)</pre>', txt, re.S):
            name = head.split(" ·")[0].strip()
            src = ROOT / "data/code" / slug / name
            if not src.exists():
                problems.append(f"blog/{slug}.html: code block {name} has no file in data/code/{slug}/")
                continue
            if _html.unescape(pre).rstrip("\n") != src.read_text(encoding="utf-8").rstrip("\n"):
                problems.append(f"blog/{slug}.html: code block {name} differs from data/code/{slug}/{name}")
            if "not executed" not in head and not re.search(r"\$ (python3|sh) " + re.escape(name), outs):
                problems.append(f"blog/{slug}.html: {name} shows no run output and is not labelled 'not executed'")
        for sec in re.split(r"<h2 ", txt)[1:]:
            title = re.sub(r"<[^>]+>", "", sec.split("</h2>")[0])
            if "scenario" in title.lower() and not re.search(r'wr-caveat"><b class="l">Scenario', sec):
                problems.append(f"blog/{slug}.html: section '{title.split('>')[-1].strip()}' is a scenario without a scenario box")
    me = Path(__file__).read_text(encoding="utf-8")
    line = [l for l in me.splitlines() if l.strip().startswith("problems = broken_links(files)")]
    for v in REQUIRED_VALIDATORS:
        if not line or (v + "(") not in line[0]:
            problems.append(f"scripts/build.py: required validator {v}() is no longer run by --check")
    return problems


def validate_hf():
    """data/hf-papers.json (generated by scripts/import_hf_papers.py): structural checks for pages/hf-paper-themes.html."""
    path = ROOT / "data/hf-papers.json"
    if not path.exists():
        return []
    d = json.loads(path.read_text(encoding="utf-8"))
    themes = {t[0] for t in d["themes"]}
    problems, now = [], date.today().strftime("%Y-%m")
    for k in ("name", "url"):
        if not d.get("source", {}).get(k):
            problems.append(f"data/hf-papers.json: source.{k} is required (attribution)")
    if any(m not in d["months"] for m in d.get("partial", [])):
        problems.append("data/hf-papers.json: partial lists a month that has no data")
    for ym, ps in d["months"].items():
        if not re.fullmatch(r"20\d\d-\d\d", ym) or not "2023-01" <= ym <= now:
            problems.append(f"data/hf-papers.json: month {ym} is invalid or out of range")
        seen = set()
        for p in ps:
            w = f"data/hf-papers.json: {ym} {p.get('id', '?')}"
            if not re.fullmatch(r"\d{4}\.\d{4,5}", p["id"]) or p["id"] in seen:
                problems.append(f"{w}: bad or duplicate arXiv id")
            seen.add(p["id"])
            if p["th"] not in themes or any(t not in themes for t in p.get("tg", [])):
                problems.append(f"{w}: unknown theme")
            if not isinstance(p["u"], int) or p["u"] < 0 or not p["ti"]:
                problems.append(f"{w}: needs a title and a non-negative integer upvote count")
    return problems


def render_idea_graph():
    """Merge data/idea-map.json (areas, lineage links, tours) with every paper card in the
    "AI Research in YEAR" articles into blog/idea-graph.json for pages/idea-map.html.
    Returns (json_text, problems)."""
    src = json.loads((ROOT / "data/idea-map.json").read_text(encoding="utf-8"))
    labels = src.get("labels", {})
    nodes, problems = [], []
    for f in sorted((ROOT / "blog").glob("ai-research-*-papers.html")):
        s = f.read_text(encoding="utf-8")
        span = f.stem[len("ai-research-"):-len("-papers")]
        years = [int(y) for y in span.split("-")]
        short = {p[0]: p for p in json.loads(re.search(r"const P = (\[\[.*?\]\]);", s).group(1))}
        legend = dict(re.findall(r'<span class="ar-b ([\w-]+)">([^<]+)</span>', s[s.find('class="ar-legend"'):][:3000]))
        for m in re.finditer(r'<div class="ar-card" id="([^"]+)">(.*?)<div class="op-refs">', s, re.S):
            cid, card = m.groups()
            key = f"{span}/{cid}"
            small = clean_text(re.search(r"<small>(.*?)</small>", card, re.S).group(1))
            year = years[0]
            if len(years) > 1:
                found = [int(y) for y in re.findall(r"\b(19\d\d|20\d\d)\b", small) if years[0] <= int(y) <= years[1]]
                year = found[0] if found else years[0]
            eli = re.search(r'<div class="ar-eli"><b>[^<]*</b><p>(.*?)</p>', card, re.S)
            desc = clean_text(eli.group(1)) if eli else ""
            first = re.match(r"(.+?[.!?])(\s|$)", desc)
            badges = [html.unescape(legend.get(b, b)) for b in short.get(cid, [0] * 5)[4]]
            nodes.append({
                "id": key, "y": year, "a": src["nodeArea"].get(key, ""),
                "t": labels.get(key) or html.unescape(short[cid][3]) if cid in short else cid,
                "e": short[cid][2] if cid in short else "•",
                "d": truncate(first.group(1) if first else desc, 190),
                "w": small, "b": badges, "p": any(w in b for b in badges for w in PRIZE_WORDS),
                "u": f"../blog/{f.name}#{cid}", "l": f"AI Research in {span.replace('-', '–')}",
            })
    keys = {n["id"] for n in nodes}
    area_ids = {a[0] for a in src["areas"]}
    problems += [f"data/idea-map.json: card {k} has no area" for k in sorted(keys) if src["nodeArea"].get(k) not in area_ids]
    problems += [f"data/idea-map.json: unknown card {k} in nodeArea" for k in src["nodeArea"] if k not in keys]
    problems += [f"data/idea-map.json: link to unknown card {x}" for l in src["links"] for x in l[:2] if x not in keys]
    problems += [f"data/idea-map.json: tour stop {x} unknown" for t in src["tours"] for x in t[1] if x not in keys]
    problems += [f"data/idea-map.json: core idea {x} unknown" for x in src.get("core", []) if x not in keys]
    out = {"generated_by": "scripts/build.py from data/idea-map.json + blog/ai-research-*-papers.html",
           "areas": src["areas"], "nodes": nodes, "links": src["links"], "tours": src["tours"], "core": src.get("core", [])}
    return json.dumps(out, ensure_ascii=False, separators=(",", ":")) + "\n", problems


