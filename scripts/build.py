def html_files():
    files = [ROOT / "index.html"]
    files += sorted((ROOT / "pages").glob("*.html"))
    files += sorted((ROOT / "blog").glob("*.html"))
    return files


def prefixes(path):
    folder = path.parent.name if path.parent != ROOT else ""
    if folder == "pages":
        return {"ROOT": "../", "PAGES": "", "BLOG": "../blog/"}
    if folder == "blog":
        return {"ROOT": "../", "PAGES": "../pages/", "BLOG": ""}
    return {"ROOT": "", "PAGES": "pages/", "BLOG": "blog/"}


def active_tab(path):
    folder, stem = path.parent.name, path.stem
    if folder == "blog" or stem == "blog":
        return "blog"
    if stem == "ai-news":
        return "news"
    if stem in ECOSYSTEM_PAGES:
        return "ecosystems"
    if stem == "frontier-model-learning":
        return "mode"
    if folder == "pages":
        return "explore"
    return None


def render_nav(template, path):
    out = template
    for key, val in prefixes(path).items():
        out = out.replace("{{%s}}" % key, val)
    active = active_tab(path)
    for tab in ("mode", "explore", "ecosystems", "blog", "news"):
        out = out.replace("{{ACTIVE_%s}}" % tab, " active" if tab == active else "")
    return f"{NAV_START}\n{out.rstrip()}\n{NAV_END}"


def div_block_end(s, start):
    depth = 0
    for m in re.finditer(r"<div\b|</div>", s[start:]):
        depth += 1 if m.group(0) == "<div" else -1
        if depth == 0:
            return start + m.end()
    raise ValueError("unbalanced div")


def replace_nav(s, block, path):
    if NAV_START in s:
        a, b = s.index(NAV_START), s.index(NAV_END) + len(NAV_END)
        return s[:a] + block + s[b:]
    a = s.find('<nav class="navbar"')
    w = s.find('<div class="nav-panel-wrap"', a)
    if a < 0 or w < 0:
        raise ValueError(f"{path}: navbar or nav-panel-wrap not found")
    return s[:a] + block + s[div_block_end(s, w):]


def clean_text(fragment):
    text = html.unescape(re.sub(r"<[^>]+>", "", fragment))
    return re.sub(r"\s+", " ", text).strip()


def truncate(text, limit=160):
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:—-") + "…"


def page_description(s):
    after_nav = s[s.find(NAV_END):] if NAV_END in s else s
    for p in re.findall(r"<p[^>]*>(.*?)</p>", after_nav, re.S):
        text = clean_text(p)
        if len(text) > 70:
            return text
    return f"{SITE_NAME} — tracking the path to AGI."


def render_seo(path, s, manifest):
    rel = path.relative_to(ROOT).as_posix()
    url = BASE_URL + ("" if rel == "index.html" else rel)
    title = clean_text(re.search(r"<title>(.*?)</title>", s, re.S).group(1))
    post = manifest.get(path.stem) if path.parent.name == "blog" else None
    if post:
        desc, og_type, og_title = post["excerpt"], "article", post["title"]
    else:
        desc, og_type, og_title = page_description(s), "website", title
    desc = html.escape(truncate(clean_text(desc)), quote=True)
    og_title = html.escape(og_title, quote=True)
    lines = [
        SEO_START,
        f'  <meta name="description" content="{desc}" />',
        f'  <link rel="canonical" href="{url}" />',
        f'  <meta property="og:site_name" content="{SITE_NAME}" />',
        f'  <meta property="og:type" content="{og_type}" />',
        f'  <meta property="og:title" content="{og_title}" />',
        f'  <meta property="og:description" content="{desc}" />',
        f'  <meta property="og:url" content="{url}" />',
        f'  <meta property="og:image" content="{OG_IMAGE}" />',
        '  <meta name="twitter:card" content="summary_large_image" />',
    ]
    if post:
        lines.append(f'  <meta property="article:published_time" content="{post["date"]}" />')
    lines.append(f"  {SEO_END}")
    return "\n".join(lines)


def replace_seo(s, block):
    return re.sub(r"[ \t]*" + re.escape(SEO_START), "  " + SEO_START, _replace_seo(s, block), count=1)


def _replace_seo(s, block):
    if SEO_START in s:
        a, b = s.index(SEO_START), s.index(SEO_END) + len(SEO_END)
        return s[:a] + block.lstrip() + s[b:]
    m = re.search(r"</title>\s*", s)
    return s[: m.end()] + "  " + block + "\n  " + s[m.end():].lstrip(" ")


def render_sitemap(files, manifest):
    rows = []
    for f in files:
        if f.name.startswith("_"):
            continue
        rel = f.relative_to(ROOT).as_posix()
        post = manifest.get(f.stem) if f.parent.name == "blog" else None
        lastmod = post["date"] if post else date.today().isoformat()
        loc = BASE_URL + ("" if rel == "index.html" else rel)
        rows.append(f"  <url><loc>{loc}</loc><lastmod>{lastmod}</lastmod></url>")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "\n".join(rows) + "\n</urlset>\n")


