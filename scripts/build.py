def load_lab_updates():
    """data/lab-updates.json → (data, problems). Items sorted newest first."""
    data = json.loads((ROOT / "data/lab-updates.json").read_text(encoding="utf-8"))
    labs, types = {l[0] for l in data["labs"]}, {t[0] for t in data["types"]}
    lo, hi = data["range"]
    problems, seen = [], set()
    for it in data["items"]:
        where = f"data/lab-updates.json: {it.get('id', '?')}"
        if not re.fullmatch(r"20\d\d-\d\d(-\d\d)?", it["date"]):
            problems.append(f"{where}: bad date {it['date']}")
        elif not lo[:len(it["date"])] <= it["date"] <= hi[:len(it["date"])]:
            problems.append(f"{where}: date {it['date']} outside {lo}..{hi}")
        if it["lab"] not in labs:
            problems.append(f"{where}: unknown lab {it['lab']}")
        if it["type"] not in types:
            problems.append(f"{where}: unknown type {it['type']}")
        if not it.get("source", "").startswith("https://"):
            problems.append(f"{where}: source must be an https:// link")
        if not it.get("title") or not it.get("summary"):
            problems.append(f"{where}: title and summary are required")
        if it["id"] in seen:
            problems.append(f"{where}: duplicate id")
        seen.add(it["id"])
    data["items"].sort(key=lambda x: (x["date"], x["lab"]), reverse=True)
    return data, problems


def fmt_lab_date(d):
    y, m, *rest = d.split("-")
    mon = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"][int(m) - 1]
    return f"{int(rest[0])} {mon} {y}" if rest else f"{mon} {y}"


